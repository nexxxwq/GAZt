"""
physics.py — физическая модель течения газа в трубопроводе.

Реализованы:
- расчёт скорости потока,
- числа Рейнольдса,
- коэффициента гидравлического сопротивления (формула Альтшуля),
- потери давления (уравнение Дарси–Вейсбаха),
- координаты утечки.

Все формулы используются для генерации целевой переменной
при обучении нейросети.
"""

import math


def velocity(Q, d):
    """
    Скорость потока газа в трубе.

    Q — объёмный расход, м^3/с
    d — диаметр трубы, м
    """
    area = math.pi * d ** 2 / 4
    return Q / area


def reynolds_number(rho, v, d, eta):
    """
    Число Рейнольдса.

    rho — плотность газа, кг/м^3
    v — скорость потока, м/с
    d — диаметр трубы, м
    eta — динамическая вязкость, Па*с
    """
    return rho * v * d / eta


def friction_coefficient(Re, k_e, d):
    """
    Коэффициент гидравлического сопротивления (формула Альтшуля).

    Re — число Рейнольдса
    k_e — эквивалентная шероховатость, м
    d — диаметр трубы, м
    """
    return 0.11 * (68 / Re + k_e / d) ** 0.25


def resistance_coefficient(lam, d, rho):
    """
    Удельное сопротивление 1 метра трубопровода.

    k = λ · ρ / (2 · d · A²), где A = π·d²/4

    Возвращает k в Па/(м³/с)²/м = кг/м⁸.
    """
    A = math.pi * d ** 2 / 4
    return lam * rho / (2 * d * A ** 2)


def pressure_loss(lam, Q, d, rho, L):
    """
    Потеря давления на участке длиной L (уравнение Дарси–Вейсбаха).

    lam — коэффициент сопротивления
    Q — расход, м^3/с
    d — диаметр, м
    rho — плотность газа, кг/м^3
    L — длина участка, м
    """
    return lam * (L / d) * (8 * Q ** 2 / (math.pi ** 2 * d ** 4)) * rho


def leak_coordinate(P_start, P_end, Q_start, Q_end, k, L):
    """
    Координата утечки вдоль трубопровода.

    Использует баланс давлений на двух участках:
        участок 1 (0..x): расход Q_start
        участок 2 (x..L): расход Q_end

    P_start, P_end — давления, Па
    Q_start, Q_end — расходы, м^3/с
    k — удельное сопротивление 1 метра, кг/м^8
    L — длина участка, м
    """
    dP_start = k * L * Q_start ** 2
    dP_end = k * L * Q_end ** 2

    if dP_start == dP_end:
        return None

    x = L * (P_start - P_end - dP_end) / (dP_start - dP_end)

    if x < 0 or x > L:
        return None

    return x